// Builds the map data shipped with VizLab from Natural Earth (public domain, https://www.naturalearthdata.com/).
//
//   node scripts/build-geo.mjs <ne_110m_admin_0_countries.geojson> <ne_10m_admin_1_states_provinces.geojson>
//
// Output: src/geo/data/world.topo.json and korea.topo.json (TopoJSON, quantised). Area (km²) is measured on the original
// geometry before simplification; Korean short names for the provinces are written by hand below.
import * as d3 from 'd3'
import { writeFileSync, readFileSync, mkdirSync } from 'node:fs'
import { topology } from 'topojson-server'
import { quantize as quantizeTopology } from 'topojson-client'
import { presimplify, simplify, quantile } from 'topojson-simplify'

const [countriesPath, adminPath] = process.argv.slice(2)
if (!countriesPath || !adminPath) throw new Error('usage: build-geo.mjs <countries.geojson> <admin1.geojson>')
const out = new URL('../src/geo/data/', import.meta.url)
mkdirSync(out, { recursive: true })

const R = 6371.0088 // mean Earth radius, km
const area = (f) => Math.round(d3.geoArea(f) * R * R)
const round = (v, d = 3) => Math.round(v * 10 ** d) / 10 ** d
const centroid = (f) => d3.geoCentroid(f).map((v) => round(v, 2))

// ── world: 177 countries of the 1:110m dataset
const world = JSON.parse(readFileSync(countriesPath, 'utf8'))
const countries = {
  type: 'FeatureCollection',
  // Antarctica is left out: it has no population statistics and Mercator cannot draw it.
  features: world.features.filter((f) => f.properties.ADM0_A3 !== 'ATA').map((f) => {
    const p = f.properties
    return {
      type: 'Feature',
      geometry: f.geometry,
      properties: { id: p.ADM0_A3, en: p.NAME, ko: p.NAME_KO, continent: p.CONTINENT, pop: p.POP_EST, popYear: p.POP_YEAR, gdp: p.GDP_MD, gdpYear: p.GDP_YEAR, area: area(f), c: centroid(f) },
    }
  }),
}
const wt = topology({ countries }, 1e4)
writeFileSync(new URL('world.topo.json', out), JSON.stringify(wt))

// ── South Korea: provinces of the 1:10m admin-1 dataset
const SHORT = { 'KR-11': '서울', 'KR-26': '부산', 'KR-27': '대구', 'KR-28': '인천', 'KR-29': '광주', 'KR-30': '대전', 'KR-31': '울산', 'KR-50': '세종', 'KR-41': '경기', 'KR-42': '강원', 'KR-43': '충북', 'KR-44': '충남', 'KR-45': '전북', 'KR-46': '전남', 'KR-47': '경북', 'KR-48': '경남', 'KR-49': '제주' }
const admin = JSON.parse(readFileSync(adminPath, 'utf8'))
const provinces = {
  type: 'FeatureCollection',
  features: admin.features.filter((f) => f.properties.adm0_a3 === 'KOR').map((f) => {
    const p = f.properties
    return { type: 'Feature', geometry: f.geometry, properties: { id: p.iso_3166_2, en: p.name, ko: SHORT[p.iso_3166_2], full: p.name_ko, area: area(f), c: centroid(f) } }
  }).sort((a, b) => a.properties.id.localeCompare(b.properties.id)),
}
if (provinces.features.length !== 17 || provinces.features.some((f) => !f.properties.ko)) throw new Error('expected 17 provinces')
let kt = presimplify(topology({ provinces }, 1e6))
kt = simplify(kt, quantile(kt, 0.97))
// Re-quantise after simplifying so the shipped coordinates are small integers.
kt = quantizeTopology(kt, 1e4)
writeFileSync(new URL('korea.topo.json', out), JSON.stringify(kt))

// Plain rows for the sample data sets, so the data tables do not have to load the map shapes.
const wr = countries.features.map((f) => f.properties).sort((a, b) => a.id.localeCompare(b.id)).map((p) => [p.id, p.ko, p.en, p.continent, Math.round(p.pop / 1e4) / 100, Math.round(p.gdp / 1e3), p.area, p.c[0], p.c[1]])
const kr = provinces.features.map((f) => f.properties).map((p) => [p.id, p.ko, p.en, p.area, p.c[0], p.c[1]])
writeFileSync(new URL('stats.ts', out), `// Generated by scripts/build-geo.mjs from Natural Earth (public domain). Do not edit by hand.
// world: [id, 한국어, English, continent, 인구(백만 명, Natural Earth 추정), GDP(십억 US$, Natural Earth 추정), 면적(km²), 경도, 위도]
export const worldRows: [string, string, string, string, number, number, number, number, number][] = ${JSON.stringify(wr)}
// korea: [ISO 3166-2, 한국어, English, 면적(km²), 경도, 위도]
export const koreaRows: [string, string, string, number, number, number][] = ${JSON.stringify(kr)}
`)

console.log('world', countries.features.length, 'countries;', 'korea', provinces.features.length, 'provinces')
