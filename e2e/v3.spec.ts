const readoutValue = (page: import('@playwright/test').Page, label: string) =>
  page.locator('.chart-readout div').filter({ has: page.locator('dt', { hasText: new RegExp(`^${label}$`) }) }).locator('dd')

async function openData(page: import('@playwright/test').Page) {
  await page.getByTestId('tab-data').click()
  await expect(page.getByTestId('data-table')).toBeVisible()
}
const cell = (page: import('@playwright/test').Page, label: string) => page.getByLabel(label, { exact: true })
async function editCell(page: import('@playwright/test').Page, label: string, value: string) {
  const input = cell(page, label)
  await input.fill(value)
  await input.press('Enter')
}

