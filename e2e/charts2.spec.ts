  test('confidence intervals: level, method, sample size and the repeated-sampling experiment', async ({ page }) => {
    await openViz(page, 'ci')
    const bars = page.getByTestId('ci-bar')
    await expect(bars).toHaveCount(4)
    const width = async () => bars.first().locator('line').first().evaluate((e) => Math.abs(Number(e.getAttribute('x2')) - Number(e.getAttribute('x1'))))
    const w95 = await width()
    await setRange(page.getByTestId('ctl-level'), 0.99)
    expect(await width()).toBeGreaterThan(w95)
    await setRange(page.getByTestId('ctl-level'), 0.8)
    expect(await width()).toBeLessThan(w95)
    await page.getByTestId('ctl-method').selectOption('bootstrap')
    await expect(bars).toHaveCount(4)
    await page.getByTestId('ctl-method').selectOption('t')
    const before = await width()
    await page.getByTestId('tab-data').click()
    await setRange(page.getByTestId('dataset-size'), 800)
    await page.getByTestId('tab-settings').click()
    await expect.poll(width).toBeLessThan(before)
    await page.getByTestId('ctl-mode').getByRole('radio', { name: '반복 표집 실험' }).click()
    await expect(page.getByTestId('ci-sim')).toHaveCount(40)
    await expect(page.getByTestId('ci-true')).toHaveCount(1)
    await setRange(page.getByTestId('ctl-sims'), 20)
    await expect(page.getByTestId('ci-sim')).toHaveCount(20)
    const miss = page.locator('[data-covers="0"]')
    const hit = page.locator('[data-covers="1"]')
    expect((await miss.count()) + (await hit.count())).toBe(20)
    expect(await hit.count()).toBeGreaterThan(10)
    const cov = await readout(page, '포함한 구간').textContent()
    await page.getByTestId('ctl-resample').click()
    await expect(readout(page, '목표 신뢰수준')).toHaveText('80%')
    expect(cov).toMatch(/\d+ \/ 20/)
  })
