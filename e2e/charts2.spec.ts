test.describe('data editing, undo/redo, reset and invalid data work in every new lab', () => {
  for (const id of V2) {
    test(id, async ({ page }) => {
      await page.goto('./')
      await page.evaluate(() => localStorage.clear())
      await openViz(page, id)
      // the calendar starts on the latest year; the table's first page holds 2023, so show that year
      if (id === 'calendar') await page.getByTestId('ctl-year').selectOption('2023')
      const svg = page.getByTestId('chart-svg')
      const before = await svg.innerHTML()
      await page.getByTestId('tab-data').click()
      const cell = page.locator('.cell-input.is-num').first()
      const original = await cell.inputValue()
      await cell.fill('123456')
      await cell.press('Enter')
      await expect(page.getByTestId('undo')).toBeEnabled()
      await expect.poll(async () => svg.innerHTML(), { timeout: 3000 }).not.toBe(before)
      await page.getByTestId('undo').click()
      await expect(cell).toHaveValue(original)
      await expect(page.getByTestId('redo')).toBeEnabled()
      await page.getByTestId('redo').click()
      await expect(cell).toHaveValue('123456')
      // text in a numeric cell is flagged, not fatal
      await cell.fill('abc')
      await cell.press('Enter')
      await expect(page.getByText('숫자가 아닌 값이 1개')).toBeVisible()
      await expect(page.getByText('이 데이터로는 그래프를 그릴 수 없습니다')).toHaveCount(0)
      await page.getByTestId('reset').click()
      await expect(page.getByText('숫자가 아닌 값')).toHaveCount(0)
      await expect(cell).toHaveValue(original)
    })
  }
})

