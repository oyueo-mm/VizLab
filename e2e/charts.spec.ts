import { dragBy, expect, openViz, readout, setRange, settle, svgPoint, test } from './fixtures'

const ids = ['scatter', 'bubble', 'hexbin', 'pairplot', 'histogram', 'kde', 'ecdf', 'box', 'violin', 'strip', 'bar', 'grouped-bar', 'stacked-bar', 'line', 'area', 'pie', 'treemap', 'heatmap', 'parallel', 'radar']

test.describe('every chart renders with data and explanations', () => {
  for (const id of ids) {
    test(id, async ({ page }) => {
      await openViz(page, id)
      const marks = page.getByTestId('chart-svg').locator('circle, rect, path, polygon, line')
      expect(await marks.count()).toBeGreaterThan(5)
      await expect(page.getByTestId('lab-canvas').locator('.chart-message')).toHaveCount(0)
      await page.getByTestId('details-toggle').click()
      const details = page.getByTestId('details-body')
      await expect(details.getByRole('heading', { name: '정의' })).toBeVisible()
      await expect(details.locator('.katex').first()).toBeVisible()
      await expect(details.locator('.related-card').first()).toBeVisible()
    })
  }
})

test.describe('chart-specific interactions', () => {
  test('scatter: add, drag and delete points; regression', async ({ page }) => {
    await openViz(page, 'scatter')
    await expect(readout(page, 'n')).toHaveText('80')
    const p = await svgPoint(page, 0.12, 0.14)
    await page.mouse.click(p.x, p.y)
    await expect(readout(page, 'n')).toHaveText('81')
    const point = page.locator('circle[data-i="5"]')
    const before = await point.getAttribute('cx')
    await dragBy(page, point, 80, -50)
    await expect(point).not.toHaveAttribute('cx', before!)
    await page.locator('circle[data-i="7"]').click()
    await page.getByTestId('delete-selected').click()
    await expect(readout(page, 'n')).toHaveText('80')
    await page.getByTestId('undo').click()
    await expect(readout(page, 'n')).toHaveText('81')
    await page.getByTestId('ctl-regression').check({ force: true })
    await expect(page.locator('.regression')).toBeVisible()
    await expect(readout(page, '회귀식')).toContainText('y =')
  })

  test('bubble: area vs radius size encoding', async ({ page }) => {
    await openViz(page, 'bubble')
    // the largest bubble maps to the maximum radius in both modes, so compare the smallest
    const c = page.locator('.mark-point').last()
    await settle(page)
    const r1 = Number(await c.getAttribute('r'))
    await page.getByTestId('ctl-sizemode').getByRole('radio', { name: '반지름 ∝ 값' }).click()
    await settle(page)
    const r2 = Number(await c.getAttribute('r'))
    expect(r2).not.toBeCloseTo(r1, 1)
  })

  test('hexbin: hexagon size and density updates', async ({ page }) => {
    await openViz(page, 'hexbin')
    const hexes = page.locator('.mark-hex')
    const small = await hexes.count()
    await setRange(page.getByTestId('ctl-radius'), 30)
    await expect.poll(() => hexes.count()).toBeLessThan(small)
    await expect(readout(page, '점')).toHaveText('2,500')
    const p = await svgPoint(page, 0.85, 0.2)
    await page.mouse.click(p.x, p.y)
    await expect(readout(page, '점')).toHaveText('2,540')
  })

  test('pair plot: variable selection changes the matrix', async ({ page }) => {
    await openViz(page, 'pairplot')
    await expect(page.locator('[data-cell]')).toHaveCount(16)
    await page.getByTestId('ctl-diagonal').getByRole('radio', { name: 'KDE' }).click()
    await page.getByTestId('tab-data').click()
    await page.getByTestId('role-vars-꽃잎 너비').uncheck()
    await expect(page.locator('[data-cell]')).toHaveCount(9)
    await page.getByTestId('role-vars-꽃잎 길이').uncheck()
    await expect(page.locator('[data-cell]')).toHaveCount(4)
  })

  test('histogram: bins, offset, normalisation and added values', async ({ page }) => {
    await openViz(page, 'histogram')
    const bars = page.locator('.mark-bar')
    await expect(bars).toHaveCount(16)
    await setRange(page.getByTestId('ctl-bins'), 30)
    await expect(bars).toHaveCount(30)
    await setRange(page.getByTestId('ctl-offset'), 0.5)
    await expect(bars).toHaveCount(31)
    await page.getByTestId('ctl-rule').selectOption('sturges')
    await expect(readout(page, '구간 수')).toHaveText('10')
    await page.getByTestId('ctl-norm').getByRole('radio', { name: '밀도' }).click()
    await expect(page.locator('.axis-label', { hasText: '밀도' })).toBeVisible()
    const p = await svgPoint(page, 0.5, 0.5)
    await page.mouse.click(p.x, p.y)
    await expect(readout(page, 'n')).toHaveText('201')
  })

  test('KDE: bandwidth and kernel reshape the curve', async ({ page }) => {
    await openViz(page, 'kde')
    const curve = page.getByTestId('kde-curve-0')
    await settle(page)
    const d0 = await curve.getAttribute('d')
    await setRange(page.getByTestId('ctl-bw'), 0.01)
    await settle(page)
    const d1 = await curve.getAttribute('d')
    expect(d1).not.toBe(d0)
    await page.getByTestId('ctl-kernel').selectOption('uniform')
    await settle(page)
    expect(await curve.getAttribute('d')).not.toBe(d1)
    // individual kernels are drawn only for ≤150 observations
    await page.getByTestId('tab-data').click()
    await setRange(page.getByTestId('dataset-size'), 60)
    await page.getByTestId('tab-settings').click()
    await page.getByTestId('ctl-kernels').check({ force: true })
    await expect(page.locator('.kernel-bump').first()).toBeAttached()
  })

  test('ECDF: add and remove samples', async ({ page }) => {
    await openViz(page, 'ecdf')
    await expect(readout(page, 'n')).toHaveText('200')
    const p = await svgPoint(page, 0.6, 0.5)
    await page.mouse.click(p.x, p.y)
    await page.mouse.move(0, 0)
    await expect(readout(page, 'n')).toHaveText('201')
    await page.locator('.rug line').first().dispatchEvent('pointerup')
    await expect(readout(page, 'n')).toHaveText('200')
    await page.getByTestId('ctl-normal').check({ force: true })
    await expect(page.locator('.normal-ref')).toBeVisible()
  })

  test('box plot: outliers follow the whisker rule and added values', async ({ page }) => {
    await openViz(page, 'box')
    const outliers = page.getByTestId('outlier')
    const base = await outliers.count()
    const band = (await page.locator('[data-group="1라인"] .box').boundingBox())!
    const svg = (await page.getByTestId('chart-svg').boundingBox())!
    await page.mouse.click(band.x + band.width / 2, svg.y + 46)
    await expect(outliers).toHaveCount(base + 1)
    await setRange(page.getByTestId('ctl-k'), 3)
    await expect.poll(() => outliers.count()).toBeLessThan(base + 1)
    await page.getByTestId('ctl-whisker').getByRole('radio', { name: '최소–최대' }).click()
    await expect(outliers).toHaveCount(0)
  })

  test('violin: bandwidth changes the density shape', async ({ page }) => {
    await openViz(page, 'violin')
    const shape = page.getByTestId('violin-shape').first()
    await settle(page)
    const d0 = await shape.getAttribute('d')
    await setRange(page.getByTestId('ctl-bw'), 2.5)
    await settle(page)
    expect(await shape.getAttribute('d')).not.toBe(d0)
    await page.getByTestId('ctl-inner').selectOption('points')
    await expect(page.locator('.box-point').first()).toBeVisible()
  })

  test('strip plot: jitter vs swarm layouts, drag to change a value', async ({ page }) => {
    await openViz(page, 'strip')
    const dot = page.locator('.mark-point').first()
    await settle(page)
    const cx = await dot.getAttribute('cx')
    await page.getByTestId('ctl-layout').getByRole('radio', { name: '스웜' }).click()
    await settle(page)
    expect(await dot.getAttribute('cx')).not.toBe(cx)
    const cy = await dot.getAttribute('cy')
    await dragBy(page, dot, 0, -60)
    await settle(page)
    expect(await dot.getAttribute('cy')).not.toBe(cy)
  })

  test('bar: sort, drag a bar, baseline warning', async ({ page }) => {
    await openViz(page, 'bar')
    const labels = page.locator('.bar-label')
    await expect(labels).toHaveText(['48', '31', '66', '27', '39', '22', '17'])
    await page.getByTestId('ctl-sort').selectOption('desc')
    await expect(labels).toHaveText(['66', '48', '39', '31', '27', '22', '17'])
    await dragBy(page, page.locator('rect[data-cat="딸기"]'), 0, -80)
    await expect(labels.first()).not.toHaveText('66')
    await page.getByTestId('ctl-zero').uncheck({ force: true })
    await expect(page.locator('.axis-warning')).toBeVisible()
  })

  test('grouped bar: legend toggles groups, swapping roles', async ({ page }) => {
    await openViz(page, 'grouped-bar')
    const bars = page.locator('.mark-bar')
    await expect(bars).toHaveCount(20)
    await page.locator('.legend-item', { hasText: '1분기' }).click()
    await expect(bars).toHaveCount(15)
    await page.getByTestId('ctl-swap').check({ force: true })
    await expect(page.locator('.legend-item', { hasText: '노트북' })).toBeVisible()
  })

  test('stacked bar: real totals and 100% mode', async ({ page }) => {
    await openViz(page, 'stacked-bar')
    await expect(page.locator('.bar-label', { hasText: /^397$/ })).toBeVisible()
    await page.getByTestId('ctl-mode').getByRole('radio', { name: '100% 비율' }).click()
    await expect(page.locator('.axis-label', { hasText: '비율' })).toBeVisible()
    await expect(page.locator('.axis text', { hasText: '100%' })).toBeVisible()
  })

  test('line: moving average and dragging points', async ({ page }) => {
    await openViz(page, 'line')
    await expect(page.getByTestId('series-line')).toHaveCount(3)
    await setRange(page.getByTestId('ctl-ma'), 4)
    await expect(page.locator('.ma-line')).toHaveCount(3)
    await page.getByTestId('ctl-curve').selectOption('step')
    const pt = page.locator('.line-point').nth(10)
    const cy = Number(await pt.getAttribute('cy'))
    await dragBy(page, pt, 0, -70)
    await settle(page)
    expect(Number(await pt.getAttribute('cy'))).toBeLessThan(cy - 30)
    await page.locator('.legend-item', { hasText: 'SNS' }).click()
    await expect(page.getByTestId('series-line')).toHaveCount(2)
  })

  test('area: stacking modes and series toggles', async ({ page }) => {
    await openViz(page, 'area')
    await expect(page.getByTestId('area-layer')).toHaveCount(3)
    await page.getByTestId('ctl-mode').getByRole('radio', { name: '100%' }).click()
    await expect(page.locator('.axis text', { hasText: '100%' })).toBeVisible()
    await page.locator('.legend-item', { hasText: '검색' }).click()
    await expect(page.getByTestId('area-layer')).toHaveCount(2)
    await page.getByTestId('ctl-mode').getByRole('radio', { name: '스트림' }).click()
    await expect(page.getByTestId('area-layer')).toHaveCount(2)
  })

  test('pie: donut, folding small slices, excluding categories', async ({ page }) => {
    await openViz(page, 'pie')
    const slices = page.getByTestId('pie-slice')
    await expect(slices).toHaveCount(7)
    await setRange(page.getByTestId('ctl-inner'), 0.6)
    await expect(page.locator('.donut-center')).toBeVisible()
    await page.locator('.legend-item', { hasText: '딸기' }).click()
    await settle(page)
    await expect(slices).toHaveCount(6)
    await setRange(page.getByTestId('ctl-other'), 0.12)
    await settle(page)
    expect(await slices.count()).toBeLessThan(6)
  })

  test('treemap: drill down and back, tiling', async ({ page }) => {
    await openViz(page, 'treemap')
    const leaves = page.getByTestId('treemap-leaf')
    const all = await leaves.count()
    await page.locator('.tm-group').first().click({ position: { x: 30, y: 6 } })
    await expect(page.locator('.treemap-crumbs button')).toHaveCount(2)
    expect(await leaves.count()).toBeLessThan(all)
    await page.locator('.treemap-crumbs button', { hasText: '전체' }).click()
    await expect(leaves).toHaveCount(all)
    await page.getByTestId('ctl-tile').selectOption('slice')
    await expect(leaves).toHaveCount(all)
  })

  test('heatmap: edit a cell, switch scale and correlation mode', async ({ page }) => {
    await openViz(page, 'heatmap')
    await page.getByTestId('hm-cell').first().click()
    await page.getByTestId('hm-input').fill('99')
    await page.getByTestId('hm-input').press('Enter')
    await expect(page.locator('.hm-value').first()).toHaveText('99')
    await page.getByTestId('ctl-scheme').selectOption('magma')
    await page.getByTestId('ctl-range').getByRole('radio', { name: '직접 지정' }).click()
    await expect(page.getByTestId('ctl-max')).toBeVisible()
    await page.getByTestId('ctl-mode').getByRole('radio', { name: '상관 행렬' }).click()
    await expect(page.getByTestId('hm-cell')).toHaveCount(49)
  })

  test('parallel coordinates: brush filter and axis order', async ({ page }) => {
    await openViz(page, 'parallel')
    await expect(page.getByTestId('pc-selected')).toHaveText('90 / 90')
    const axis = page.locator('[data-axis-body]').first()
    const b = (await axis.boundingBox())!
    await page.mouse.move(b.x + b.width / 2, b.y + b.height * 0.1)
    await page.mouse.down()
    await page.mouse.move(b.x + b.width / 2, b.y + b.height * 0.3, { steps: 5 })
    await page.mouse.move(b.x + b.width / 2, b.y + b.height * 0.45, { steps: 5 })
    await page.mouse.up()
    await expect(page.getByTestId('pc-selected')).not.toHaveText('90 / 90')
    await page.getByTestId('clear-filters').click()
    await expect(page.getByTestId('pc-selected')).toHaveText('90 / 90')
    await expect(page.locator('.pc-title').first()).toContainText('배기량')
    await page.getByRole('button', { name: '배기량 오른쪽으로' }).click()
    await expect(page.locator('.pc-title').first()).toContainText('마력')
  })

  test('radar: add, delete and drag series values', async ({ page }) => {
    await openViz(page, 'radar')
    const shapes = page.getByTestId('radar-shape')
    await expect(shapes).toHaveCount(3)
    await page.getByTestId('radar-add').click()
    await expect(shapes).toHaveCount(4)
    await page.getByTestId('radar-delete').first().click()
    await expect(shapes).toHaveCount(3)
    const before = await shapes.first().getAttribute('points')
    await dragBy(page, page.locator('.radar-vertex').first(), 0, 60)
    await settle(page)
    expect(await shapes.first().getAttribute('points')).not.toBe(before)
  })
})
